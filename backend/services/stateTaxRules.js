/**
 * Get rules for a specific state by code
 */
export function getStateRules(stateCode) {
  return STATE_TAX_RULES[stateCode] || null;
}

/**
 * Get all state codes
 */
export function getAllStateCodes() {
  return Object.keys(STATE_TAX_RULES);
}

/**
 * Get states that have income tax
 */
export function getIncomeTaxStates() {
  return Object.entries(STATE_TAX_RULES)
    .filter(([, rules]) => rules.hasIncomeTax)
    .map(([code]) => code);
}

/**
 * Get states with no income tax
 */
export function getNoIncomeTaxStates() {
  return Object.entries(STATE_TAX_RULES)
    .filter(([, rules]) => !rules.hasIncomeTax)
    .map(([code]) => code);
}

/**
 * Estimate state income tax for a given state and taxable income
 * Uses simplified bracket calculation for estimation purposes only.
 */
export function estimateStateIncomeTax(stateCode, taxableIncome) {
  const rules = STATE_TAX_RULES[stateCode];
  if (!rules || !rules.hasIncomeTax || !rules.incomeTaxBrackets.length) return 0;

  let tax = 0;
  for (const bracket of rules.incomeTaxBrackets) {
    if (taxableIncome <= 0) break;
    const taxable = Math.min(taxableIncome, (bracket.max === Infinity ? taxableIncome : bracket.max) - bracket.min);
    if (taxable > 0) {
      tax += taxable * bracket.rate;
      taxableIncome -= taxable;
    }
  }
  return Math.max(0, tax);
}

/**
 * Return all state options formatted for UI dropdowns
 */
export function getStateOptions() {
  return Object.entries(STATE_TAX_RULES).map(([code, rules]) => ({
    value: code,
    label: `${rules.name} (${code})`,
  }));
}

export default STATE_TAX_RULES;
